// inRanges 升序区间表线性判定（与 TS 版 inRanges 同为线性扫描语义）。
func inRanges(code rune, ranges []codePointRange) bool {
	for _, r := range ranges {
		if code < r.lo {
			return false
		}
		if code <= r.hi {
			return true
		}
	}
	return false
}

// terminalCharWidth 单个码点在终端里占的列数：码点 < 0x0300 恒 1；零宽 0、半角 1、
// 全角与中文 2。
func terminalCharWidth(r rune) int {
	if r < 0x0300 {
		return 1
	}
	if inRanges(r, zeroWidthRanges) {
		return 0
	}
	if inRanges(r, wideRanges) {
		return 2
	}
	return 1
}
