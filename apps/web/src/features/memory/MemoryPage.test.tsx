import { act, fireEvent, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import type { AgentMemoryProposal } from '@elysian/contracts'
import { createMockGateway } from '../../adapters/mock/gateway'
import { renderApp } from '../../test/renderApp'
import { useAgentMemoryStore } from '../../stores/agentMemoryStore'
import { useSessionStore } from '../../stores/sessionStore'

beforeEach(() => { useAgentMemoryStore.getState().reset(); useSessionStore.setState({ phase: 'authed', mode: 'demo' }) })
describe('Wiki 文档工作台', () => {
  it('创建页面并人工编辑，版本历史保留原文', async () => {
    const user = userEvent.setup(), gateway = createMockGateway({ eventStream: 'memory' })
    renderApp('/agent/memory', { gateway })
    await waitFor(() => expect(screen.getByRole('button', { name: '新建页面' })).toBeEnabled())
    await user.click(screen.getByRole('button', { name: '新建页面' }))
    const dialog = screen.getByRole('dialog')
    await user.type(within(dialog).getByLabelText('标题'), 'Nginx 运维')
    await user.type(within(dialog).getByLabelText('页面标识'), 'operations/nginx')
    fireEvent.change(within(dialog).getByLabelText('Markdown 正文'), { target: { value: '# 检查配置\n\n执行前先检查。' } })
    await user.click(within(dialog).getByRole('button', { name: '保存页面' }))
    expect(await screen.findByRole('heading', { name: 'Nginx 运维' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: '编辑' }))
    fireEvent.change(screen.getByLabelText('Markdown 正文'), { target: { value: '先检查，再重载。' } })
    await user.click(screen.getByRole('button', { name: '保存页面' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    expect(await screen.findByText('先检查，再重载。')).toBeInTheDocument()
    const pages = await gateway.agentMemory.listPages('wiki-global')
    expect(pages[0]).toMatchObject({ revision: 2, maintenance: 'manual' })
    expect((await gateway.agentMemory.getRevision('wiki-global', pages[0]!.id, 1)).markdown).toContain('检查配置')
  })
  it('固定历史链接只读，回退创建新修订，HTML不执行', async () => {
    const user = userEvent.setup(), gateway = createMockGateway({ eventStream: 'memory' })
    const first = await gateway.agentMemory.createPage('wiki-global', { slug: 'safe', title: '历史页面', markdown: '原文<script>danger()</script>', evidence: [{ id: 'ev-1', kind: 'conversation', text: '保留的来源摘录', createdAt: '2026-10-20T00:00:00Z', digest: 'digest', originalCleared: true }] })
    await gateway.agentMemory.updatePage(first.spaceId, first.id, { ...first, expectedRevision: 1, markdown: '新版' })
    renderApp(`/agent/memory?space=wiki-global&page=${first.id}&revision=1`, { gateway })
    expect(await screen.findByRole('heading', { name: '历史页面' })).toBeInTheDocument()
    expect(screen.getByText('正在查看固定历史修订 1。')).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: '编辑' })).not.toBeInTheDocument()
    expect(screen.getByText('保留的来源摘录')).toBeInTheDocument()
    expect(screen.getByText('原始内容已清理，此处保留来源摘录。')).toBeInTheDocument()
    expect(screen.getByRole('article', { name: 'Wiki 文档' }).querySelector('script')).toBeNull()
    await user.click(screen.getByRole('button', { name: '回退到此版本' }))
    await user.click(screen.getByRole('button', { name: '确认回退' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    expect(await gateway.agentMemory.getPage(first.spaceId, first.id)).toMatchObject({ revision: 3, markdown: first.markdown, maintenance: 'manual' })
  })
  it('导入先限制UTF-8字节，成功保存原文且演示明确不生成页面', async () => {
    const user = userEvent.setup(), gateway = createMockGateway({ eventStream: 'memory' })
    const models = await gateway.modelSettings.listModelProfiles()
    const model = models.find(model => model.active && model.hasCredential && model.capabilities.text && model.capabilities.tools)!
    vi.spyOn(gateway.modelSettings, 'listModelProfiles').mockResolvedValue([{ ...model, id: 'text-only', model: '仅文本模型', capabilities: { ...model.capabilities, tools: false } }, ...models])
    renderApp('/agent/memory', { gateway })
    await waitFor(() => expect(screen.getByRole('button', { name: '导入资料' })).toBeEnabled())
    await user.click(screen.getByRole('button', { name: '导入资料' }))
    expect(screen.queryByRole('option', { name: /仅文本模型/ })).not.toBeInTheDocument()
    await user.type(screen.getByLabelText('资料标题'), '交接资料')
    await user.selectOptions(screen.getByLabelText('整理模型'), model.id)
    fireEvent.change(screen.getByLabelText('粘贴或编辑原文'), { target: { value: '汉'.repeat(5500) } })
    await user.click(screen.getByRole('button', { name: '保存并开始整理' }))
    expect(await screen.findByText('单份资料不能超过 16 KiB')).toBeInTheDocument()
    expect(await gateway.agentMemory.listPages('wiki-global')).toHaveLength(0)
    fireEvent.change(screen.getByLabelText('粘贴或编辑原文'), { target: { value: '交接原文。' } })
    await user.click(screen.getByRole('button', { name: '保存并开始整理' }))
    expect(await screen.findByRole('heading', { name: '交接资料' })).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: '编辑' })).not.toBeInTheDocument()
    expect(await screen.findByText('本地演示已保存原文；自动整理需要真实后端与模型，未生成页面。')).toBeInTheDocument()
    expect(await gateway.agentMemory.listPages('wiki-global')).toHaveLength(1)
    await user.click(screen.getByRole('button', { name: '版本记录' }))
    expect(screen.getByText('导入原文不可改写；更新资料请重新导入。')).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: '恢复自动维护' })).not.toBeInTheDocument()
  })
  it('重新登录按当前地址恢复所选空间和固定修订，并重新读取公开内容', async () => {
    const user = userEvent.setup(), gateway = createMockGateway({ eventStream: 'memory' })
    const space = await gateway.agentMemory.createSpace({ name: '项目知识', kind: 'business' })
    const first = await gateway.agentMemory.createPage(space.id, { slug: 'guide', title: '项目指南', markdown: '原始指南' })
    await gateway.agentMemory.updatePage(space.id, first.id, { ...first, markdown: '最新指南', expectedRevision: 1 })
    renderApp('/agent/memory', { gateway })
    await waitFor(() => expect(screen.getByRole('combobox', { name: '知识空间' })).toHaveValue('wiki-global'))
    await user.selectOptions(screen.getByRole('combobox', { name: '知识空间' }), space.id)
    await user.click(await screen.findByRole('button', { name: /项目指南/ }))
    await user.click(await screen.findByRole('button', { name: '版本记录' }))
    await user.click(screen.getByRole('button', { name: /修订 1/ }))
    expect(await screen.findByText('正在查看固定历史修订 1。')).toBeInTheDocument()
    const read = vi.spyOn(gateway.agentMemory, 'getRevision')
    act(() => useSessionStore.setState({ phase: 'anonymous' }))
    expect(screen.queryByRole('heading', { name: '项目指南' })).not.toBeInTheDocument()
    expect(useAgentMemoryStore.getState().pages).toHaveLength(0)
    act(() => useSessionStore.setState({ phase: 'authed' }))
    expect(await screen.findByText('正在查看固定历史修订 1。')).toBeInTheDocument()
    expect(screen.getByRole('combobox', { name: '知识空间' })).toHaveValue(space.id)
    expect(read).toHaveBeenCalledWith(space.id, first.id, 1)
  })
  it('冲突复核固定所见修订，冲突后回读并按新修订采纳，收到回执才移除候选', async () => {
    const user = userEvent.setup(), gateway = createMockGateway({ eventStream: 'memory' })
    const first = await gateway.agentMemory.createPage('wiki-global', { slug: 'guide', title: '当前指南', markdown: '人工维护原文' })
    const proposal: AgentMemoryProposal = { id: 'candidate-1', spaceId: first.spaceId, pageId: first.id, status: 'pending', reason: 'manual-protection', originKind: 'extraction', originId: 'job-1', createdAt: first.createdAt, page: { slug: first.slug, title: '建议指南', markdown: '整理后的建议内容', expectedRevision: 0 } }
    let accepted = false
    vi.spyOn(gateway.agentMemory, 'listProposals').mockImplementation(async () => accepted ? [] : [{ ...proposal, currentPage: await gateway.agentMemory.getPage(first.spaceId, first.id) }])
    let resolve!: (receipt: AgentMemoryProposal) => void
    const decide = vi.spyOn(gateway.agentMemory, 'decideProposal').mockRejectedValueOnce(new Error('Wiki 页面版本已变化，请重新读取')).mockImplementation(() => new Promise(done => { resolve = done }))
    renderApp('/agent/memory', { gateway })
    await user.click(await screen.findByRole('button', { name: '待确认 1' }))
    expect(screen.getByText('此页面由人工维护，自动整理的修改需要你确认。')).toBeInTheDocument()
    expect(within(screen.getByRole('region', { name: '当前页面内容' })).getByText('人工维护原文')).toBeInTheDocument()
    expect(within(screen.getByRole('region', { name: '建议页面内容' })).getByText('整理后的建议内容')).toBeInTheDocument()
    await gateway.agentMemory.updatePage(first.spaceId, first.id, { ...first, markdown: '并发更新正文', expectedRevision: 1 })
    await act(() => useAgentMemoryStore.getState().refresh(gateway))
    // 后台刷新不能替换管理员已经在看的基准。
    expect(screen.getByRole('button', { name: '基于修订 1 采纳' })).toBeEnabled()
    await user.click(screen.getByRole('button', { name: '基于修订 1 采纳' }))
    expect(decide).toHaveBeenNthCalledWith(1, proposal.id, 'approved', 1)
    expect(await screen.findByText('尚未确认采纳。请重新读取当前版本，核对后再提交。')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: '基于修订 1 采纳' })).toBeDisabled()
    expect(screen.getByRole('heading', { name: '建议指南' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: '重新读取当前版本' }))
    expect(await screen.findByText('并发更新正文')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: '基于修订 2 采纳' }))
    expect(decide).toHaveBeenNthCalledWith(2, proposal.id, 'approved', 2)
    expect(screen.getByRole('heading', { name: '建议指南' })).toBeInTheDocument()
    accepted = true
    await act(async () => resolve({ ...proposal, status: 'approved' }))
    expect(await screen.findByText('没有待确认的修改。')).toBeInTheDocument()
  })
  it('候选目标已撤回时保留对照内容并禁止采纳，未知原因使用中文说明', async () => {
    const user = userEvent.setup(), gateway = createMockGateway({ eventStream: 'memory' })
    const page = await gateway.agentMemory.createPage('wiki-global', { slug: 'old', title: '旧文档', markdown: '旧内容' })
    const currentPage = await gateway.agentMemory.withdrawPage(page.spaceId, page.id, page.revision)
    vi.spyOn(gateway.agentMemory, 'listProposals').mockResolvedValue([{ id: 'candidate-2', spaceId: page.spaceId, pageId: page.id, status: 'pending', reason: 'unknown-reason', originKind: 'extraction', originId: 'job-2', createdAt: page.createdAt, currentPage, page: { slug: page.slug, title: '建议文档', markdown: '建议内容', expectedRevision: 1 } }])
    renderApp('/agent/memory', { gateway })
    await user.click(await screen.findByRole('button', { name: '待确认 1' }))
    expect(screen.getByText('此页面的修改需要人工复核。')).toBeInTheDocument()
    expect(screen.getByText('当前页面已撤回，不能采纳此修改。')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: '基于修订 2 采纳' })).toBeDisabled()
    expect(screen.getByRole('button', { name: '拒绝' })).toBeEnabled()
  })
})
